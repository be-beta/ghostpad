const DICTIONARIES: Record<Lang, Dictionary> = { pt, en, es };

let current: Lang = "pt";

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

/** Idioma do sistema, se for um dos três; senão, português. */
export function detectLang(): Lang {
  const tag = navigator.language.slice(0, 2).toLowerCase();
  return tag === "en" || tag === "es" ? tag : "pt";
}

/** Texto traduzido, com `{variáveis}` substituídas. */
export function t(key: keyof Dictionary, vars?: Record<string, string | number>): string {
  const text = DICTIONARIES[current][key];
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

/**
 * Traduz o HTML estático.
 *
 * Elementos marcados com `data-i18n` (texto), `data-i18n-title` (dica) e
 * `data-i18n-aria` (rótulo acessível) são atualizados a cada troca de idioma.
 */
export function applyStaticTranslations(root: ParentNode = document): void {
  for (const node of root.querySelectorAll<HTMLElement>("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n as keyof Dictionary);
  }
  for (const node of root.querySelectorAll<HTMLElement>("[data-i18n-title]")) {
    node.title = t(node.dataset.i18nTitle as keyof Dictionary);
  }
  for (const node of root.querySelectorAll<HTMLElement>("[data-i18n-aria]")) {
    node.setAttribute("aria-label", t(node.dataset.i18nAria as keyof Dictionary));
  }
}
